#!/usr/bin/env python3
"""
Hardware Profiler for AI Competition Multi-Agent System.
Inspects machine specs, memory, GPU/MPS, disk, and ML runtime libraries.
Writes the output to .hardware_profile.md.
"""

import os
import sys
import platform
import shutil
import subprocess
from pathlib import Path

def get_cpu_info():
    system = platform.system()
    cores = os.cpu_count() or 1
    cpu_model = platform.processor() or "Unknown"
    
    if system == "Darwin":
        try:
            res = subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output=True, text=True, check=True)
            if res.stdout.strip():
                cpu_model = res.stdout.strip()
        except Exception:
            pass
    elif system == "Linux":
        try:
            with open("/proc/cpuinfo", "r") as f:
                for line in f:
                    if "model name" in line:
                        cpu_model = line.split(":", 1)[1].strip()
                        break
        except Exception:
            pass
            
    return {"model": cpu_model, "logical_cores": cores}

def get_ram_info():
    system = platform.system()
    total_gb = 0.0
    avail_gb = 0.0
    
    try:
        import psutil
        vm = psutil.virtual_memory()
        total_gb = vm.total / (1024**3)
        avail_gb = vm.available / (1024**3)
        return {"total_gb": round(total_gb, 2), "avail_gb": round(avail_gb, 2)}
    except ImportError:
        pass

    if system == "Darwin":
        try:
            res = subprocess.run(["sysctl", "-n", "hw.memsize"], capture_output=True, text=True, check=True)
            total_bytes = int(res.stdout.strip())
            total_gb = total_bytes / (1024**3)
            avail_gb = total_gb * 0.6  # approximation fallback
        except Exception:
            pass
    elif system == "Linux":
        try:
            with open("/proc/meminfo", "r") as f:
                for line in f:
                    if "MemTotal" in line:
                        total_kb = int(line.split()[1])
                        total_gb = total_kb / (1024**2)
                    elif "MemAvailable" in line:
                        avail_kb = int(line.split()[1])
                        avail_gb = avail_kb / (1024**2)
        except Exception:
            pass
            
    return {"total_gb": round(total_gb, 2), "avail_gb": round(avail_gb, 2)}

def get_disk_info(target_path="."):
    usage = shutil.disk_usage(target_path)
    return {
        "total_gb": round(usage.total / (1024**3), 2),
        "free_gb": round(usage.free / (1024**3), 2),
        "used_gb": round(usage.used / (1024**3), 2)
    }

def get_ml_runtime_info():
    info = {
        "cuda_available": False,
        "cuda_device_name": None,
        "mps_available": False,
        "packages": {}
    }
    
    # Check PyTorch
    try:
        import torch
        info["packages"]["torch"] = torch.__version__
        if torch.cuda.is_available():
            info["cuda_available"] = True
            info["cuda_device_name"] = torch.cuda.get_device_name(0)
            info["cuda_device_count"] = torch.cuda.device_count()
        if hasattr(torch.backends, "mps") and torch.backends.mps.is_available():
            info["mps_available"] = True
    except ImportError:
        info["packages"]["torch"] = "Not Installed"

    # Other common libraries
    common_libs = ["numpy", "scipy", "pandas", "sklearn", "lightgbm", "xgboost", "catboost"]
    for lib in common_libs:
        try:
            mod = __import__(lib)
            info["packages"][lib] = getattr(mod, "__version__", "Installed")
        except ImportError:
            info["packages"][lib] = "Not Installed"
            
    return info

def generate_profile(output_file=".hardware_profile.md"):
    cpu = get_cpu_info()
    ram = get_ram_info()
    disk = get_disk_info(".")
    ml = get_ml_runtime_info()
    
    accel = "None (CPU only)"
    if ml["cuda_available"]:
        accel = f"CUDA ({ml.get('cuda_device_name', 'GPU')} x {ml.get('cuda_device_count', 1)})"
    elif ml["mps_available"]:
        accel = "Apple Silicon MPS (Metal Performance Shaders - GPU Acceleration)"

    content = f"""# Hardware & System Profile

*Auto-generated by hardware-profiler skill. Read by `optimizer` before crafting technical specifications.*

## System Overview
- **OS**: {platform.system()} {platform.release()} ({platform.machine()})
- **Architecture**: {platform.machine()}
- **Python Executable**: `{sys.executable}` ({platform.python_version()})

## Compute & Memory
- **CPU**: {cpu['model']}
- **Logical CPU Cores**: {cpu['logical_cores']}
- **Total RAM**: {ram['total_gb']} GB
- **Estimated Available RAM**: {ram['avail_gb']} GB
- **Disk Free**: {disk['free_gb']} GB (of {disk['total_gb']} GB total)

## Acceleration & ML Hardware
- **Hardware Acceleration**: **{accel}**
- **CUDA Available**: `{ml['cuda_available']}`
- **Apple MPS Available**: `{ml['mps_available']}`

## Installed Core ML Libraries
"""
    for pkg, ver in ml["packages"].items():
        content += f"- **{pkg}**: `{ver}`\n"

    content += """
## Guidance for `optimizer`:
1. **Device Allocation**: If MPS is available on Apple Silicon, use `device = torch.device('mps')`.
2. **Batch Sizing**: Keep active batch tensors sized comfortably within available unified RAM to prevent swapping.
3. **DataLoaders**: Set `num_workers = min(4, CPU cores)` to avoid excessive multiprocessing memory overhead.
"""

    out_path = Path(output_file)
    out_path.write_text(content, encoding="utf-8")
    print(f"Hardware profile generated successfully at: {out_path.resolve()}")

if __name__ == "__main__":
    out_file = sys.argv[1] if len(sys.argv) > 1 else ".hardware_profile.md"
    generate_profile(out_file)
